"""Hot-path microbenchmark: frame bytes -> normalized event -> state -> bus.

Feeds pre-serialised Binance-format frames (generated by the simulator's
book model, no network) straight into ``Engine.on_frame`` and reports
throughput and the per-frame latency distribution measured by the engine's
own instrumentation. Run with ``--profile`` to get a cProfile breakdown.

    python benchmarks/bench_hotpath.py [--frames 200000] [--profile]
"""

from __future__ import annotations

import argparse
import cProfile
import platform
import pstats
import random
import sys
import time

import orjson

from marketintel.config import DataSource, Settings
from marketintel.engine import Engine, UniverseResult
from marketintel.sim.fake_exchange import FakeBinance


def make_frames(n: int, seed: int = 3) -> tuple[list[bytes], list[str]]:
    sim = FakeBinance(seed=seed)
    frames: list[bytes] = []
    orig = sim._send

    def capture(stream, data):
        frames.append(orjson.dumps({"stream": stream, "data": data}))
        return True

    sim._send = capture  # type: ignore[method-assign]
    sim._subs = {}
    while len(frames) < n:
        sim.step(0.01, 50)
        sim.emit_depth()
    sim._send = orig  # type: ignore[method-assign]
    return frames[:n], list(sim.syms)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=200_000)
    ap.add_argument("--profile", action="store_true")
    args = ap.parse_args()

    frames, symbols = make_frames(args.frames)
    s = Settings(data_source=DataSource.REPLAY, api={"enabled": False})
    eng = Engine(s, UniverseResult(symbols, {}, False, "bench"), rest=None)
    for sh in eng.shards:
        sh.health.connected = True
    shard_of = {sym: eng.shards[i] for i, p in enumerate(eng.plans) for sym in p.symbols}
    routed = []
    for f in frames:
        d = orjson.loads(f)["data"]
        routed.append((f, shard_of[d["s"]]))
    random.Random(0).shuffle(routed[:0])

    on_frame = eng.on_frame
    mono = time.monotonic_ns
    wall = time.time_ns

    def run():
        for raw, sh in routed:
            on_frame(raw, mono(), wall(), sh)

    # Warm-up pass on a copy so state/dicts are populated, then reset metrics.
    run_n = len(routed)
    if args.profile:
        pr = cProfile.Profile()
        pr.enable()
        run()
        pr.disable()
        pstats.Stats(pr).sort_stats("tottime").print_stats(18)
        return
    t0 = time.perf_counter()
    run()
    dt = time.perf_counter() - t0
    eng.lat_state.roll()
    eng.lat_parse.roll()
    kinds = dict(eng.events)
    print(f"python {platform.python_version()} on {platform.machine()} / {platform.processor() or 'cpu'}")
    print(f"frames: {run_n:,}  {kinds}  invalid={dict(eng.invalid)}")
    print(f"throughput: {run_n / dt:,.0f} frames/s single core ({dt * 1e6 / run_n:.2f} us/frame incl. timestamping)")
    print(f"recv->normalized   (us): {eng.lat_parse.summary()['window']}")
    print(f"recv->state+publish (us): {eng.lat_state.summary()['window']}")


if __name__ == "__main__":
    sys.exit(main())
